 * ── v2.2.3（2026-09-23）：行序改「离今天近优先」＋ 数据件 sha1 指纹 ─────────
 *   缘起（由上一条的取证直接推出来的）：v2.2.2 修好「失败不发声」之后，外部取证
 *         确认包已是 2.2.2、数据表却仍空；再等 9 分钟仍**逐项一字未变**。
 *         停在这里会得出「导入没跑」的错结论。真正的原因是**导入在跑，只是行序不对**：
 *      · 导入是**逐跳**推进的（每跳 400 行 / 18 秒，靠 meta refresh 自动续跑），
 *        故**行序 = 数据到达页面的先后**；
 *      · 而数据件原是**时间升序**：`daily_site` 的「今天」在第 **14,061** 行
 *        （＝ (2026-09-23 − 2025-09-18) × 38 + 1），「未来预告」要的事件件排在
 *        它**之后**（第 29,299 行起）⇒ 前 35 跳读的全是与今天无关的日期；
 *      · 于是「点了导入、等 9 分钟、页面没反应」是**必然**，
 *        而用户合理地判成「已完成 / 坏了」。
 *   修法（数据层，见 make_datasets.py）：
 *     W1 行序改「**离今天近优先**」。daily / daily_site 按与今天的天数距离升序
 *        （同距离未来优先）；events_past 按**月日的环形距离**升序（同月日内年份倒序，
 *        与页面 `ORDER BY jd_core DESC` 一致）；events_future 时间升序本身即由近及远。
 *        ⇒ 第一跳就写入「今天那 38 行」与「本日的历史条目」，
 *          今日栏与本日历史栏**几秒内**即正常，不必等全量跑完。
 *     W2 清单 `_manifest.json` 的每个数据集增 `sha1` 与 `order` 两字段，
 *        顶层增 `anchor_date`（行序锚点）。
 *   修法（导入器，本版本代码侧）：
 *     W3 导入前的守卫从「比**字节数**」升级为「比 **sha1**」。
 *        ★ 这是必须的，不是加保险：**重排行序不改变文件字节数** ——
 *          实测四个数据件重排前后字节数**一字节不差**
 *          （2,325,814 / 13,201,509 / 193,484 / 7,821,702），
 *          而 sha1 全部改变。只比字节数 ⇒ 判不出变更 ⇒ 沿用旧字节位落在**行中间**
 *          ⇒ fgets 读回半行 ⇒ JSON 解析失败被记成坏行 ⇒ **后半段静默丢失**，
 *          且游标照常推进、页面照常报「已完成」。upsert 幂等，故重导只花时间、不重复行。
 *     W4 数据件 sha1 与**清单声明值**不符 ⇒ 当场拒跑并说清（多半是上传不完整，
 *        或清单与数据件不是同一次生成）。宁可不动手，也不许写进一批来历不明的数据。
 *     W5 后台页新增「**数据件自检**」区：每件列出 行序 / **第 1 行是谁** / sha1 /
 *        与清单是否一致，并显示行序锚点。把「行序错了、包没换」这两件
 *        原先**在外面完全看不出来**的事，变成页面上的一行字。
 *   无表结构变更 ⇒ **KCJ_ASTRO_SCHEMA 仍为 3**。
