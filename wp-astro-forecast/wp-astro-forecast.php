    //   原 §7 预留位已撤销：不再留「待补」标记，避免被误读为未完成的缺口。
    //   ⇒ 本函数产出**不含**【7】、不含「杨主席」、不含「核心论点」。

    $L[] = '以上条目由邝楚嘉搜集整理。'
