 *        而是**先解析** DDL 再与现状比对；解析器认不出的部分它**不报错、只是不做**。
 *        于是会出现「4 张表里 3 张建好、第 4 张永远缺着」，而两头都看不到原因：
 *          · init 守卫那边：`width_shortfalls()` 因「列读不到」判不合格 ⇒ 不写 schema
 *            option ⇒ **每次请求都白跑一遍 dbDelta**（永远重试、永远不成功）；
 *          · 页面那边：只显示「仍缺失」，用户转述不出原因 ⇒ 外部只能靠猜（本轮猜了两轮）。
 *        ⇒ `KCJ_Astro_DB::create()` 增**直连 `CREATE TABLE IF NOT EXISTS` 兜底**：
 *          只对「确实不存在」的表用（已存在的表不动，列宽升级仍归 dbDelta），
 *          并把 `$wpdb->last_error` **记进 schema_error、并显示在页面上**
 *          （没有原始错误时，「建不出来」这句话在站外等于没有信息）。
