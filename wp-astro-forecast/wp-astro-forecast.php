 *   F59 **每跳只推进一个集 ⇒ 先到的不一定是先要的**：原实现每跳只跑一个集，
 *        于是「先跑完 `daily_site` 的 74 跳，历史栏才轮到」——按「每行一次查询 ＋
 *        一次写」估算，那是 **20 分钟以上**。
