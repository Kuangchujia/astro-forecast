 *   F57 **队头阻塞**：原实现只取「第一个未完成的集」当 target，它一报错就
 *        `return WP_Error` ⇒ **整条链中断** ⇒ 排在它后面的集**永远轮不到**。
 *        而 `daily_site` 在清单里排第 2 位，又恰是最可能报错的那个（表缺或列不匹配）
 *        ⇒ `events_past`（4,672 行）**从未被导入** ——「历史栏一直空」与
