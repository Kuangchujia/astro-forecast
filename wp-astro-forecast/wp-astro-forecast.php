 * ── v2.2.2（2026-09-23）：导入器的四处「失败不发声」 ────────────────────
 *   缘起：用户报「已全部完成」，而线上「今日天象」仍降级、「历史今日」仍全空。
 *         外部取证发现两头对不上 —— events_future（145 行，在清单里排在 daily_site
 *         **之后**）已完整入库（报告按未来 12 个月过滤后正好显示 62 条，逐字吻合）；
 *         而 daily_site（29,298 行）在页面上已被算作「完成」，却查不到 2026-09-23
 *         （该日期在数据件第 14,061 行 ＝ (2026-09-23 − 2025-09-18) × 38 + 1）。
 *   四处根因（共同点：出错不发声）：
 *     F53 **写入失败不中断、游标照推** ⇒ 目标表不存在或列不匹配时，页面显示
 *         「已完成 100% ＋ 成功 0 / 失败 29298」，**看上去像成功**。
 *         现：进 `kcj_astro_import_run()` 先做**目标表存在性前置检查**，缺表即刻报错；
 *         `failed > 0` 以 `notice-error` 显性呈现失败行数与前三条原因；
 *         并加「补建 / 升级表结构」按钮（`kcj_run=repair`）—— 当场 dbDelta ＋ 实测复验，
 *         不再只靠 init 守卫（守卫一旦因 option 被误写而停止重试，表就永远缺着）。
 *     F54 页面上看不到「表在不在」⇒ 新增**表结构自检区**：4 张表逐张列存在性与现存
 *         行数，使「表不存在」与「表存在但空」肉眼可分。
 *     F55 `kcj_astro_import_read()` 每跳都从文件头 fgets 到 offset ⇒ 对 29,298 行的
 *         数据件是 **O(n²)**，越跑越慢、最后像卡死。现游标增记**字节位 pos** ＋ 数据件
 *         字节数 size：一致则 fseek 直读；不一致（数据件被换过）则**从第 1 行重导**并
 *         如实报出，绝不静默错位。分块 120 → 400，跳数再降一个量级。
 *     F56 游标按「成功行数」推进（`$offset += count($rows)`）⇒ 文件里只要有 1 行非法
 *         JSON，该行永远重读（死循环）；兜底 `if (!$rows) { $offset = $total; }` 更糟，
 *         会**静默跳过后面所有行**却报「已完成」。现改按 **consumed（消费行数）** 推进，
 *         兜底收窄为「一行都没消费到」。
